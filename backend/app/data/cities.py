def normalize_city(name: str) -> str | None:
    """把用户输入归一化为城市库中的标准名；不支持则返回 None。"""
    if not name:
        return None
    key = _normalize(name)
    if key in _NORMALIZED:
        return _NORMALIZED[key]
    # 容错：允许「北京朝阳区」这类带区县后缀的输入
    for known, standard in _NORMALIZED.items():
        if key.startswith(known) or known.startswith(key):
            return standard
    return None


def is_supported(name: str) -> bool:
    return normalize_city(name) is not None


def city_tier(name: str) -> str:
    """城市等级：tier1 / new_tier1 / tier2 / tier3（用于 M2 打标）。"""
    standard = normalize_city(name) or name
    if standard in TIER1:
        return "tier1"
    if standard in NEW_TIER1:
        return "new_tier1"
    if standard in TIER2:
        return "tier2"
    return "tier3"


