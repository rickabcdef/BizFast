// 按关键字模糊过滤（去重）
export function filterCities(keyword: string, limit = 50): string[] {
  const k = keyword.trim()
  if (!k) return CITIES.slice(0, limit)
  return CITIES.filter((c) => c.includes(k)).slice(0, limit)
}

// 定位自动识别（Web 端优先用浏览器 Geolocation，失败返回 null 由 UI 降级）
// 注意：真实「经纬度->城市」需后端逆地理，这里仅做能力封装，返回 null 触发手动选择。
export async function autoDetectCity(): Promise<string | null> {
  try {
    if (typeof navigator !== 'undefined' && navigator.geolocation) {
      // 浏览器定位成功，但城市名需后端解析；此处只返回「已授权」，UI 仍提供手动选择
      return null
    }
  } catch {
    return null
  }
  return null
}
